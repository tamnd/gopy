// ReplacementFunc dispatches on a recognized identifier inside a uop body.
// It returns (reachable, error): reachable=false means the dispatched
// keyword unconditionally exits the surrounding statement.
//
// CPython: Tools/cases_generator/generators_common.py:92-94 ReplacementFunctionType
type ReplacementFunc func(
	tkn Token,
	it *TokenIterator,
	uop CodeSection,
	storage *Storage,
	inst *Instruction,
) (bool, error)

// Emitter walks a CodeSection body, dispatching keyword identifiers
// through a replacement registry and emitting the rest verbatim.
//
// CPython: Tools/cases_generator/generators_common.py:107-131 Emitter
type Emitter struct {
	Out       *CWriter
	Labels    map[string]*Label
	replacers map[string]ReplacementFunc
}

// NewEmitter builds an Emitter wired to the default replacement registry.
//
// CPython: Tools/cases_generator/generators_common.py:112-131 Emitter.__init__
func NewEmitter(out *CWriter, labels map[string]*Label) *Emitter {
	e := &Emitter{Out: out, Labels: labels}
	e.replacers = map[string]ReplacementFunc{
		"EXIT_IF":                      e.ExitIf,
		"DEOPT_IF":                     e.DeoptIf,
		"ERROR_IF":                     e.ErrorIf,
		"ERROR_NO_POP":                 e.ErrorNoPop,
		"DECREF_INPUTS":                e.DecrefInputs,
		"DEAD":                         e.Kill,
		"INPUTS_DEAD":                  e.KillInputs,
		"SYNC_SP":                      e.SyncSp,
		"SAVE_STACK":                   e.SaveStack,
		"RELOAD_STACK":                 e.ReloadStack,
		"PyStackRef_CLOSE_SPECIALIZED": e.StackrefCloseSpecialized,
		"PyStackRef_AsPyObjectSteal":   e.StackrefSteal,
		"DISPATCH":                     e.Dispatch,
		"INSTRUCTION_SIZE":             e.InstructionSize,
		"stack_pointer":                e.StackPointer,
	}
	return e
}

// Replacers exposes the dispatch table for callers (e.g. for derived
// generators that want to override individual entries).
func (e *Emitter) Replacers() map[string]ReplacementFunc { return e.replacers }

// SetReplacer overrides one entry in the dispatch table.
func (e *Emitter) SetReplacer(name string, fn ReplacementFunc) {
	e.replacers[name] = fn
}

// Emit is a thin wrapper around CWriter.Emit accepting Token or string.
//
// CPython: Tools/cases_generator/generators_common.py:671-672 Emitter.emit
func (e *Emitter) Emit(v any) { e.Out.Emit(v) }

// Dispatch handles the bare DISPATCH() identifier: it must be reached
// with the stack already reloaded.
//
// CPython: Tools/cases_generator/generators_common.py:133-144 Emitter.dispatch
func (e *Emitter) Dispatch(
	tkn Token, _ *TokenIterator, _ CodeSection, storage *Storage, _ *Instruction,
) (bool, error) {
	if storage.Spilled != 0 {
		return false, analysisError("stack_pointer needs reloading before dispatch", tkn)
	}
	e.Emit(tkn)
	return false, nil
}

// DeoptIf rewrites DEOPT_IF(cond); into the standard if-block plus the
// JUMP_TO_PREDICTED tail. Returns false (unreachable past) when the
// condition is the literal true/1.
//
// CPython: Tools/cases_generator/generators_common.py:146-169 Emitter.deopt_if
func (e *Emitter) DeoptIf(
	_ Token, it *TokenIterator, _ CodeSection, _ *Storage, inst *Instruction,
) (bool, error) {
	e.Out.StartLine()
	e.Out.Emit("if (")
	lparen, ok := it.Next()
	if !ok || lparen.Kind != TokLParen {
		return false, analysisError("Expected '(' after DEOPT_IF", lparen)
	}
	first, hasFirst := it.Peek()
	if _, err := emitTo(e.Out, it, TokRParen); err != nil {
		return false, err
	}
	e.Emit(") {\n")
	if _, ok := it.Next(); !ok { // semicolon
		return false, analysisError("Expected ';' after DEOPT_IF", lparen)
	}
	if inst == nil || inst.Family == nil {
		return false, analysisError("DEOPT_IF requires an instruction with a family", lparen)
	}
	familyName := inst.Family.Name
	e.Emit(fmt.Sprintf("UPDATE_MISS_STATS(%s);\n", familyName))
	e.Emit(fmt.Sprintf("assert(_PyOpcode_Deopt[opcode] == (%s));\n", familyName))
	e.Emit(fmt.Sprintf("JUMP_TO_PREDICTED(%s);\n", familyName))
	e.Emit("}\n")
	return !alwaysTrue(first, hasFirst), nil
}

// ExitIf is identical to DeoptIf in upstream (`exit_if = deopt_if`).
//
// CPython: Tools/cases_generator/generators_common.py:171 Emitter.exit_if
func (e *Emitter) ExitIf(
	tkn Token, it *TokenIterator, uop CodeSection, storage *Storage, inst *Instruction,
) (bool, error) {
	return e.DeoptIf(tkn, it, uop, storage, inst)
}

// gotoError renders the matching JUMP_TO_LABEL(...) for an offset.
//
// CPython: Tools/cases_generator/generators_common.py:173-178 Emitter.gotoTknerror
func (e *Emitter) gotoError(offset int, storage *Storage) string {
	if offset > 0 {
		return fmt.Sprintf("JUMP_TO_LABEL(pop_%d_error);", offset)
	}
	if offset < 0 {
		_ = storage.Copy().Flush(e.Out)
	}
	return "JUMP_TO_LABEL(error);"
}

// ErrorIf rewrites ERROR_IF(cond); into the if/jump pair.
//
// CPython: Tools/cases_generator/generators_common.py:180-213 Emitter.error_if
func (e *Emitter) ErrorIf(
	tkn Token, it *TokenIterator, _ CodeSection, storage *Storage, _ *Instruction,
) (bool, error) {
	lparen, ok := it.Next()
	if !ok || lparen.Kind != TokLParen {
		return false, analysisError("Expected '(' after ERROR_IF", tkn)
	}
	first, hasFirst := it.Peek()
	unconditional := alwaysTrue(first, hasFirst)
	if unconditional {
		if _, ok := it.Next(); !ok {
			return false, analysisError("Truncated ERROR_IF", tkn)
		}
		if _, ok := it.Next(); !ok { // RPAREN
			return false, analysisError("Truncated ERROR_IF", tkn)
		}
		e.Out.StartLine()
	} else {
		e.Out.EmitAt("if ", tkn)
		e.Emit(lparen)
		if _, err := emitTo(e.Out, it, TokRParen); err != nil {
			return false, err
		}
		e.Out.Emit(") {\n")
	}
	if _, ok := it.Next(); !ok { // semicolon
		return false, analysisError("Expected ';' after ERROR_IF", tkn)
	}
	if err := storage.ClearInputs("at ERROR_IF"); err != nil {
		return false, err
	}
	cOffset := storage.Stack.SpOffset()
	offset, err := atoiStrict(cOffset)
	if err != nil {
		offset = -1
	}
	e.Out.Emit(e.gotoError(offset, storage))
	e.Out.Emit("\n")
	if !unconditional {
		e.Out.Emit("}\n")
	}
	return !unconditional, nil
}

