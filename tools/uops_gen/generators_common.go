// emitStmt dispatches a statement to its specific emitter.
//
// CPython: Tools/cases_generator/generators_common.py:456-467 Emitter._emit_stmt
func (e *Emitter) emitStmt(
	stmt Stmt, uop CodeSection, storage *Storage, inst *Instruction,
) (bool, *Token, *Storage, error) {
	switch s := stmt.(type) {
	case *SimpleStmt:
		return e.emitSimpleStmt(s, uop, storage, inst)
	case *MacroIfStmt:
		return e.emitMacroIfStmt(s, uop, storage, inst)
	case *IfStmt:
		return e.emitIfStmt(s, uop, storage, inst)
	case *BlockStmt:
		return e.emitBlockStmt(s, uop, storage, inst, true)
	case *ForStmt:
		return e.emitForStmt(s, uop, storage, inst)
	case *WhileStmt:
		return e.emitWhileStmt(s, uop, storage, inst)
	}
	return false, nil, storage, fmt.Errorf("emitStmt: unsupported %T", stmt)
}

// emitSimpleStmt walks the tokens of a simple statement, dispatching
// each recognized identifier through the replacement registry.
//
// CPython: Tools/cases_generator/generators_common.py:469-521 Emitter.emit_SimpleStmt
func (e *Emitter) emitSimpleStmt(
	stmt *SimpleStmt, uop CodeSection, storage *Storage, inst *Instruction,
) (bool, *Token, *Storage, error) {
	localStores := map[Token]struct{}{}
	for _, t := range uop.GetLocalStores() {
		localStores[t] = struct{}{}
	}
	reachable := true
	var lastTkn Token
	if len(stmt.Contents) > 0 {
		lastTkn = stmt.Contents[len(stmt.Contents)-1]
	}
	props := uop.GetProperties()
	if escape, ok := props.EscapingCalls[stmt]; ok {
		if escape.Kills != nil {
			if _, err := e.stackrefKill(*escape.Kills, storage, true); err != nil {
				return false, nil, storage, err
			}
		}
		e.emitSave(storage)
	}
	it := NewTokenIterator(stmt.Contents)
	for {
		tkn, ok := it.Next()
		if !ok {
			break
		}
		lastTkn = tkn
		switch tkn.Kind {
		case TokGoto:
			labelTkn, ok := it.Next()
			if !ok {
				return false, nil, storage, analysisError("Expected label after goto", tkn)
			}
			if err := e.gotoLabel(tkn, labelTkn, storage); err != nil {
				return false, nil, storage, err
			}
			reachable = false
		case TokReturn:
			e.Emit(tkn)
			semi, err := emitTo(e.Out, it, TokSemi)
			if err != nil {
				return false, nil, storage, err
			}
			e.Emit(semi)
			reachable = false
		case TokIdentifier:
			if fn, ok := e.replacers[tkn.Text]; ok {
				ok2, err := fn(tkn, it, uop, storage, inst)
				if err != nil {
					var se *StackError
					if errors.As(err, &se) {
						return false, nil, storage, analysisError(se.Msg, tkn)
					}
					return false, nil, storage, err
				}
				if !ok2 {
					reachable = false
				}
			} else {
				if _, isStore := localStores[tkn]; isStore {
					for _, v := range storage.Inputs {
						if v.Name() == tkn.Text {
							v.InLocal = true
							v.MemoryOffset = nil
							break
						}
					}
					for _, v := range storage.Outputs {
						if v.Name() == tkn.Text {
							v.InLocal = true
							v.MemoryOffset = nil
							break
						}
					}
				}
				if strings.HasPrefix(tkn.Text, "DISPATCH") {
					reachable = false
				}
				e.Out.Emit(tkn)
			}
		default:
			e.Out.Emit(tkn)
		}
	}
	if _, ok := props.EscapingCalls[stmt]; ok {
		if err := e.emitReload(storage); err != nil {
			var se *StackError
			if errors.As(err, &se) {
				return false, nil, storage, analysisError(se.Msg, lastTkn)
			}
			return false, nil, storage, err
		}
	}
	return reachable, nil, storage, nil
}

// emitMacroIfStmt walks both arms of a #if and merges the resulting storages.
//
// CPython: Tools/cases_generator/generators_common.py:524-555 Emitter.emit_MacroIfStmt
func (e *Emitter) emitMacroIfStmt(
	stmt *MacroIfStmt, uop CodeSection, storage *Storage, inst *Instruction,
) (bool, *Token, *Storage, error) {
	e.Out.Emit(stmt.Condition)
	branch := stmt.Else != nil
	reachable := true
	var elseStorage *Storage
	if branch {
		elseStorage = storage.Copy()
	}
	for _, s := range stmt.Body {
		r, tkn, st, err := e.emitStmt(s, uop, storage, inst)
		if err != nil {
			return false, nil, storage, err
		}
		storage = st
		if tkn != nil {
			e.Out.Emit(*tkn)
		}
		if !r {
			reachable = false
		}
	}
	if branch {
		e.Out.Emit(*stmt.Else)
		for _, s := range stmt.ElseBody {
			r, tkn, st, err := e.emitStmt(s, uop, elseStorage, inst)
			if err != nil {
				return false, nil, storage, err
			}
			elseStorage = st
			if tkn != nil {
				e.Out.Emit(*tkn)
			}
			if !r {
				reachable = false
			}
		}
		if err := elseStorage.Merge(storage, e.Out); err != nil {
			return false, nil, storage, err
		}
		storage = elseStorage
	}
	e.Out.Emit(stmt.Endif)
	return reachable, nil, storage, nil
}

// emitIfStmt rewrites an if/else with merged storage at the join.
//
// CPython: Tools/cases_generator/generators_common.py:558-597 Emitter.emit_IfStmt
func (e *Emitter) emitIfStmt(
	stmt *IfStmt, uop CodeSection, storage *Storage, inst *Instruction,
) (bool, *Token, *Storage, error) {
	e.Out.Emit(stmt.If)
	for _, t := range stmt.Condition {
		e.Out.Emit(t)
	}
	ifStorage := storage.Copy()
	rbrace := &stmt.If
	reachable, rb, ifStorage2, err := e.emitStmt(stmt.Body, uop, ifStorage, inst)
	if err != nil {
		return false, rb, storage, err
	}
	if rb != nil {
		rbrace = rb
	}
	ifStorage = ifStorage2
	if stmt.Else != nil {
		e.Out.Emit(*rbrace)
		e.Out.Emit(*stmt.Else)
	}
	if stmt.ElseBody != nil {
		elseReachable, rb2, elseStorage, err := e.emitStmt(stmt.ElseBody, uop, storage, inst)
		if err != nil {
			return false, rb2, storage, err
		}
		if rb2 != nil {
			rbrace = rb2
		}
		switch {
		case !reachable:
			reachable = elseReachable
			storage = elseStorage
		case !elseReachable:
			storage = ifStorage
		default:
			if err := elseStorage.Merge(ifStorage, e.Out); err != nil {
				return false, rbrace, storage, err
			}
			storage = elseStorage
		}
	} else {
		if reachable {
			if err := ifStorage.Merge(storage, e.Out); err != nil {
				return false, rbrace, storage, err
			}
			storage = ifStorage
		} else {
			reachable = true
		}
	}
	return reachable, rbrace, storage, nil
}

// emitBlockStmt walks a brace-delimited body, optionally emitting the braces.
//
// CPython: Tools/cases_generator/generators_common.py:599-623 Emitter.emit_BlockStmt
func (e *Emitter) emitBlockStmt(
	stmt *BlockStmt, uop CodeSection, storage *Storage, inst *Instruction, emitBraces bool,
) (bool, *Token, *Storage, error) {
	if emitBraces {
		e.Out.Emit(stmt.Open)
	}
	reachable := true
	for _, s := range stmt.Body {
		r, tkn, st, err := e.emitStmt(s, uop, storage, inst)
		if err != nil {
			return false, &stmt.Close, storage, err
		}
		storage = st
		if tkn != nil {
			e.Out.Emit(*tkn)
		}
		if !r {
			reachable = false
			break
		}
	}
	closeTok := stmt.Close
	return reachable, &closeTok, storage, nil
}

// emitForStmt walks the header tokens then descends into the body.
//
// CPython: Tools/cases_generator/generators_common.py:625-636 Emitter.emit_ForStmt
func (e *Emitter) emitForStmt(
	stmt *ForStmt, uop CodeSection, storage *Storage, inst *Instruction,
) (bool, *Token, *Storage, error) {
	e.Out.Emit(stmt.For)
	for _, t := range stmt.Header {
		e.Out.Emit(t)
	}
	return e.emitStmt(stmt.Body, uop, storage, inst)
}

// emitWhileStmt walks the condition then descends into the body.
//
// CPython: Tools/cases_generator/generators_common.py:638-649 Emitter.emit_WhileStmt
func (e *Emitter) emitWhileStmt(
	stmt *WhileStmt, uop CodeSection, storage *Storage, inst *Instruction,
) (bool, *Token, *Storage, error) {
	e.Out.Emit(stmt.While)
	for _, t := range stmt.Condition {
		e.Out.Emit(t)
	}
	return e.emitStmt(stmt.Body, uop, storage, inst)
}

// EmitTokens is the entrypoint that rewrites a CodeSection's body.
//
// CPython: Tools/cases_generator/generators_common.py:652-669 Emitter.emit_tokens
func (e *Emitter) EmitTokens(
	code CodeSection, storage *Storage, inst *Instruction, emitBraces bool,
) (bool, *Storage, error) {
	e.Out.StartLine()
	reachable, tkn, storage, err := e.emitBlockStmt(code.GetBody(), code, storage, inst, emitBraces)
	if err != nil {
		return false, storage, err
	}
	if tkn == nil {
		return false, storage, fmt.Errorf("emit_tokens: missing closing brace")
	}
	if reachable {
		if err := storage.PushOutputs(); err != nil {
			var se *StackError
			if errors.As(err, &se) {
				return false, storage, analysisError(se.Msg, *tkn)
			}
			return false, storage, err
		}
	}
	if emitBraces {
		e.Out.Emit(*tkn)
	}
	return reachable, storage, nil
}

// CFlags renders the C flags string for a Properties bag, mirroring
// the upstream cflags() helper.
//
// CPython: Tools/cases_generator/generators_common.py:675-708 cflags
func CFlags(p *Properties) string {
	var flags []string
	if p.Oparg {
		flags = append(flags, "HAS_ARG_FLAG")
	}
	if p.UsesCoConsts {
		flags = append(flags, "HAS_CONST_FLAG")
	}
	if p.UsesCoNames {
		flags = append(flags, "HAS_NAME_FLAG")
	}
	if p.Jumps {
		flags = append(flags, "HAS_JUMP_FLAG")
	}
	if p.HasFree {
		flags = append(flags, "HAS_FREE_FLAG")
	}
	if p.UsesLocals {
		flags = append(flags, "HAS_LOCAL_FLAG")
	}
	if p.EvalBreaker {
		flags = append(flags, "HAS_EVAL_BREAK_FLAG")
	}
	if p.Deopts {
		flags = append(flags, "HAS_DEOPT_FLAG")
	}
	if p.SideExit {
		flags = append(flags, "HAS_EXIT_FLAG")
	}
	if !p.Infallible() {
		flags = append(flags, "HAS_ERROR_FLAG")
	}
	if p.ErrorWithoutPop {
		flags = append(flags, "HAS_ERROR_NO_POP_FLAG")
	}
	if p.Escapes {
		flags = append(flags, "HAS_ESCAPES_FLAG")
	}
	if p.Pure {
		flags = append(flags, "HAS_PURE_FLAG")
	}
	if p.NoSaveIP {
		flags = append(flags, "HAS_NO_SAVE_IP_FLAG")
	}
	if len(flags) == 0 {
		return "0"
	}
	return strings.Join(flags, " | ")
}
