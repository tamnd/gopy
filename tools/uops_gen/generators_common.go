// KillInputs marks every input dead without emitting anything.
//
// CPython: Tools/cases_generator/generators_common.py:250-263 Emitter.kill_inputs
func (e *Emitter) KillInputs(
	tkn Token, it *TokenIterator, _ CodeSection, storage *Storage, _ *Instruction,
) (bool, error) {
	for i := 0; i < 3; i++ {
		if _, ok := it.Next(); !ok {
			return false, analysisError("Truncated INPUTS_DEAD", tkn)
		}
	}
	for _, v := range storage.Inputs {
		v.Kill()
	}
	return true, nil
}

// Kill marks DEAD(name); the named input dead.
//
// CPython: Tools/cases_generator/generators_common.py:265-286 Emitter.kill
func (e *Emitter) Kill(
	tkn Token, it *TokenIterator, _ CodeSection, storage *Storage, _ *Instruction,
) (bool, error) {
	if _, ok := it.Next(); !ok { // LPAREN
		return false, analysisError("Truncated DEAD", tkn)
	}
	nameTkn, ok := it.Next()
	if !ok {
		return false, analysisError("Truncated DEAD", tkn)
	}
	name := nameTkn.Text
	if _, ok := it.Next(); !ok { // RPAREN
		return false, analysisError("Truncated DEAD", tkn)
	}
	if _, ok := it.Next(); !ok { // SEMI
		return false, analysisError("Truncated DEAD", tkn)
	}
	for _, v := range storage.Inputs {
		if v.Name() == name {
			v.Kill()
			return true, nil
		}
	}
	return false, analysisError(
		fmt.Sprintf("'%s' is not a live input-only variable", name),
		nameTkn,
	)
}

// stackrefKill closes a single PyStackRef by name, optionally checking
// that no later live local prevents an escaping close.
//
// CPython: Tools/cases_generator/generators_common.py:288-305 Emitter.stackref_kill
func (e *Emitter) stackrefKill(name Token, storage *Storage, escapes bool) (bool, error) {
	live := ""
	for i := len(storage.Inputs) - 1; i >= 0; i-- {
		v := storage.Inputs[i]
		if v.Name() == name.Text {
			if live != "" && escapes {
				return false, analysisError(
					fmt.Sprintf("Cannot close '%s' when '%s' is still live", name.Text, live),
					name,
				)
			}
			v.Kill()
			break
		}
		if v.InLocal {
			live = v.Name()
		}
	}
	return true, nil
}

// StackrefCloseSpecialized handles PyStackRef_CLOSE_SPECIALIZED(name, dealloc).
//
// CPython: Tools/cases_generator/generators_common.py:307-335 Emitter.stackref_close_specialized
func (e *Emitter) StackrefCloseSpecialized(
	tkn Token, it *TokenIterator, _ CodeSection, storage *Storage, _ *Instruction,
) (bool, error) {
	e.Out.Emit(tkn)
	lp, ok := it.Next()
	if !ok || lp.Kind != TokLParen {
		return false, analysisError("Expected '(' after PyStackRef_CLOSE_SPECIALIZED", tkn)
	}
	e.Out.Emit(lp)
	name, ok := it.Next()
	if !ok {
		return false, analysisError("Expected identifier", tkn)
	}
	e.Out.Emit(name)
	comma, ok := it.Next()
	if !ok || comma.Kind != TokComma {
		return false, analysisError("Expected comma", comma)
	}
	e.Out.Emit(comma)
	dealloc, ok := it.Next()
	if !ok || dealloc.Kind != TokIdentifier {
		return false, analysisError("Expected identifier", dealloc)
	}
	e.Out.Emit(dealloc)
	if name.Kind == TokIdentifier {
		_, escapes := nonEscapingDeallocs[dealloc.Text]
		return e.stackrefKill(name, storage, !escapes)
	}
	rparen, err := emitTo(e.Out, it, TokRParen)
	if err != nil {
		return false, err
	}
	e.Emit(rparen)
	return true, nil
}

