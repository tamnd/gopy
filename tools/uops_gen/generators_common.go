// TokenIterator is a positionable cursor over a token slice with one
// slot of look-ahead, mirroring the upstream generator.
//
// CPython: Tools/cases_generator/generators_common.py:19-44 TokenIterator
type TokenIterator struct {
	tokens []Token
	pos    int
}

// NewTokenIterator wraps a token slice as an iterator.
//
// CPython: Tools/cases_generator/generators_common.py:24-26 TokenIterator.__init__
func NewTokenIterator(tkns []Token) *TokenIterator {
	return &TokenIterator{tokens: tkns}
}

// Next returns the next token and true, or a zero Token and false at EOF.
//
// CPython: Tools/cases_generator/generators_common.py:31-37 TokenIterator.__next__
func (it *TokenIterator) Next() (Token, bool) {
	if it.pos >= len(it.tokens) {
		return Token{}, false
	}
	t := it.tokens[it.pos]
	it.pos++
	return t, true
}

// Peek returns the next token without advancing, or zero Token and false.
//
// CPython: Tools/cases_generator/generators_common.py:39-44 TokenIterator.peek
func (it *TokenIterator) Peek() (Token, bool) {
	if it.pos >= len(it.tokens) {
		return Token{}, false
	}
	return it.tokens[it.pos], true
}

// rootRelativePath echoes the upstream helper, returning a path that
// is relative to projectRoot when possible and the original otherwise.
//
// CPython: Tools/cases_generator/generators_common.py:50-55 root_relative_path
func rootRelativePath(filename, projectRoot string) string {
	if projectRoot == "" {
		return filepath.ToSlash(filename)
	}
	abs, err := filepath.Abs(filename)
	if err != nil {
		return filepath.ToSlash(filename)
	}
	rel, err := filepath.Rel(projectRoot, abs)
	if err != nil || strings.HasPrefix(rel, "..") {
		return filepath.ToSlash(filename)
	}
	return filepath.ToSlash(rel)
}

// typeAndNull returns (decltype, null_literal) for a stack item.
//
// CPython: Tools/cases_generator/generators_common.py:58-64 type_and_null
func typeAndNull(v *StackItem) (string, string) {
	switch {
	case v.Type != "":
		return v.Type, "NULL"
	case v.IsArray():
		return "_PyStackRef *", "NULL"
	default:
		return "_PyStackRef", "PyStackRef_NULL"
	}
}

// writeHeader writes the generator banner that opens every emitted file.
//
// CPython: Tools/cases_generator/generators_common.py:67-76 write_header
func writeHeader(generator string, sources []string, out io.Writer, comment, projectRoot string) error {
	if comment == "" {
		comment = "//"
	}
	parts := make([]string, 0, len(sources))
	for _, s := range sources {
		parts = append(parts, rootRelativePath(s, projectRoot))
	}
	_, err := fmt.Fprintf(out,
		"%s This file is generated by %s\n%s from:\n%s   %s\n%s Do not edit!\n",
		comment, rootRelativePath(generator, projectRoot),
		comment,
		comment, strings.Join(parts, ", "),
		comment,
	)
	return err
}

// emitTo copies tokens straight to out until it sees a top-level token
// matching kind. The matched token is consumed and returned.
//
// CPython: Tools/cases_generator/generators_common.py:79-89 emit_to
func emitTo(out *CWriter, it *TokenIterator, end string) (Token, error) {
	parens := 0
	for {
		tkn, ok := it.Next()
		if !ok {
			var anchor Token
			if it.pos > 0 {
				anchor = it.tokens[it.pos-1]
			}
			return Token{}, analysisError(
				fmt.Sprintf("Expecting %s. Reached end of file", end),
				anchor,
			)
		}
		if tkn.Kind == end && parens == 0 {
			return tkn, nil
		}
		switch tkn.Kind {
		case TokLParen:
			parens++
		case TokRParen:
			parens--
		}
		out.Emit(tkn)
	}
}

// alwaysTrue reports whether tkn is the boolean literal "true" or "1".
//
// CPython: Tools/cases_generator/generators_common.py:96-99 always_true
func alwaysTrue(tkn Token, ok bool) bool {
	if !ok {
		return false
	}
	return tkn.Text == "true" || tkn.Text == "1"
}

