// Command parser_gen generates the PEG parser table for gopy from
// cpython/Grammar/python.gram. It is the Go-targeted counterpart of
// CPython's Tools/peg_generator/.
//
// Inputs:
//   - $CPYTHON/Grammar/python.gram: the PEG grammar.
//
// Output:
//   - <repo>/parser/pegen/parser_gen.go: the rule-table struct, the
//     keyword tables, and the per-rule parse functions.
//
// Run with:
//
//	go run ./tools/parser_gen \
//	  -cpython=$HOME/github/python/cpython \
//	  -out=parser/pegen/parser_gen.go
//
// The full per-rule emitter is the next milestone. Today the
// generator extracts the rule list from python.gram and emits a
// stable scaffold: rule-id constants, a generated rule-name table,
// and a Dispatch entry point that returns ErrParserNotImplemented.
// Downstream code can program against the stable shape and the
// emitter will fill in real bodies in v0.6.
package main

import (
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"strings"
)

func main() {
	var cpython, out string
	flag.StringVar(&cpython, "cpython", "", "path to a cpython 3.14 checkout")
	flag.StringVar(&out, "out", "parser/pegen/parser_gen.go", "output Go file")
	flag.Parse()
	if cpython == "" {
		log.Fatal("parser_gen: -cpython is required")
	}
	gram := filepath.Join(cpython, "Grammar", "python.gram")
	if _, err := os.Stat(gram); err != nil {
		log.Fatalf("parser_gen: cannot read %s: %v", gram, err)
	}
	rules, err := readGrammar(gram)
	if err != nil {
		log.Fatalf("parser_gen: %v", err)
	}
	if err := writeStub(out, rules); err != nil {
		log.Fatalf("parser_gen: %v", err)
	}
	fmt.Fprintf(os.Stderr, "parser_gen: wrote %d rules to %s\n", len(rules), out)
}

type rule struct {
	Name string
	Body string
}

func readGrammar(path string) ([]rule, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	return splitRules(data), nil
}

func splitRules(src []byte) []rule {
	var rules []rule
	var cur rule
	flush := func() {
		if cur.Name != "" {
			rules = append(rules, cur)
			cur = rule{}
		}
	}
	for _, line := range splitLines(src) {
		if len(line) == 0 || line[0] == '#' {
			continue
		}
		if line[0] != ' ' && line[0] != '\t' {
			flush()
			i := 0
			for i < len(line) && line[i] != ':' && line[i] != ' ' && line[i] != '[' {
				i++
			}
			name := string(line[:i])
			if !isRuleName(name) {
				continue
			}
			cur.Name = name
			cur.Body = string(line)
			continue
		}
		cur.Body += "\n" + string(line)
	}
	flush()
	return rules
}

func isRuleName(s string) bool {
	if s == "" {
		return false
	}
	for i, c := range s {
		switch {
		case c >= 'a' && c <= 'z':
		case c >= 'A' && c <= 'Z':
		case c == '_':
		case (c >= '0' && c <= '9') && i > 0:
		default:
			return false
		}
	}
	return true
}

func splitLines(src []byte) [][]byte {
	var out [][]byte
	start := 0
	for i, b := range src {
		if b == '\n' {
			out = append(out, src[start:i])
			start = i + 1
		}
	}
	if start < len(src) {
		out = append(out, src[start:])
	}
	return out
}

func writeStub(path string, rules []rule) error {
	var sb strings.Builder
	sb.WriteString("// Code generated by tools/parser_gen from cpython/Grammar/python.gram. DO NOT EDIT.\n")
	sb.WriteString("//\n// CPython: Grammar/python.gram\n\n")
	sb.WriteString("package pegen\n\n")
	sb.WriteString("import \"errors\"\n\n")
	sb.WriteString("// ErrParserNotImplemented is returned by Dispatch while the\n")
	sb.WriteString("// per-rule emitter is offline. Callers detect this sentinel\n")
	sb.WriteString("// and route through the fixture-driven path until the real\n")
	sb.WriteString("// rule bodies land.\n")
	sb.WriteString("var ErrParserNotImplemented = errors.New(\"pegen: generated rule bodies not yet emitted\")\n\n")

	sb.WriteString("// Generated rule ids. The values are dense small ints in\n")
	sb.WriteString("// declaration order; they are stable across regenerations\n")
	sb.WriteString("// only as long as python.gram does not insert or reorder\n")
	sb.WriteString("// rules. The pegen runtime keys the memo cache on these.\n")
	sb.WriteString("const (\n")
	for i, r := range rules {
		fmt.Fprintf(&sb, "\tRule_%s = %d\n", r.Name, i)
	}
	sb.WriteString(")\n\n")

	sb.WriteString("// GeneratedRuleNames is the parallel name table. Index\n")
	sb.WriteString("// by Rule_<name>. Used by debug logging and by the\n")
	sb.WriteString("// generator round-trip checksum test.\n")
	sb.WriteString("var GeneratedRuleNames = []string{\n")
	for _, r := range rules {
		fmt.Fprintf(&sb, "\t%q,\n", r.Name)
	}
	sb.WriteString("}\n\n")

	sb.WriteString("// Dispatch is the entry point the top-level Parse driver\n")
	sb.WriteString("// calls. It picks the rule for m and invokes the\n")
	sb.WriteString("// generated body. While the emitter is offline this\n")
	sb.WriteString("// returns ErrParserNotImplemented for every mode.\n")
	sb.WriteString("//\n")
	sb.WriteString("// CPython: Parser/parser.c entry-point dispatch\n")
	sb.WriteString("func Dispatch(p *Parser, m StartRule) (any, error) {\n")
	sb.WriteString("\t_ = p\n")
	sb.WriteString("\t_ = m\n")
	sb.WriteString("\treturn nil, ErrParserNotImplemented\n")
	sb.WriteString("}\n")

	return os.WriteFile(path, []byte(sb.String()), 0o644)
}
