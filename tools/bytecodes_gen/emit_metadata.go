// Metadata emitter (B7). Walks the parsed bytecodes.c AST and
// produces a Go source file with the static stack-effect, oparg
// width, and family flags every opcode carries. The compile package
// (1628 assembler) and the VM dispatch loop both consume this table.
//
// CPython: Tools/cases_generator/tier1_generator.py + the
// `pycore_opcode_metadata.h` template.

package main

import (
	"fmt"
	"sort"
	"strings"
)

// MetadataEntry is the serialisable shape for one opcode's static
// metadata. Counts are -1 when an input/output is variadic (sized via
// `[oparg]`) since CPython encodes that as "compute at runtime".
type MetadataEntry struct {
	Name      string
	Pushes    int  // count of stack outputs, or -1 if variadic
	Pops      int  // count of stack inputs, or -1 if variadic
	CacheSize int  // total cache-effect size in code units
	HasOparg  bool // false for nullary inst defs
	Family    string
}

// stackCounts tallies the input and output stack effects of an
// instruction. A `[size]` annotation marks the slot as variadic and
// forces the count to -1.
func stackCounts(inputs []Input, outputs []Output) (pops, pushes int) {
	for _, in := range inputs {
		if in.Stack == nil {
			continue
		}
		if in.Stack.Size != "" {
			pops = -1
			break
		}
		pops++
	}
	for _, out := range outputs {
		if out.Stack == nil {
			continue
		}
		if out.Stack.Size != "" {
			pushes = -1
			break
		}
		pushes++
	}
	return
}

// cacheCount sums the cache effects across the input list.
func cacheCount(inputs []Input) int {
	n := 0
	for _, in := range inputs {
		if in.Cache != nil {
			n += in.Cache.Size
		}
	}
	return n
}

// hasOparg returns true when the instruction's body or signature
// references oparg. For v0.6 we approximate by scanning the body
// tokens for an "oparg" identifier; this matches what the upstream
// generator does before its action translator runs.
func hasOparg(body []dslTok) bool {
	for _, t := range body {
		if t.Kind == tokIdentifier && t.Text == "oparg" {
			return true
		}
	}
	return false
}

// CollectMetadata walks defs and emits one MetadataEntry per real
// `inst` (skipping `op` fragments — those only exist as components of
// macros). Family membership is filled from the FamilyDef list.
func CollectMetadata(defs []Def) []MetadataEntry {
	families := map[string]string{}
	for _, d := range defs {
		f, ok := d.(*FamilyDef)
		if !ok {
			continue
		}
		for _, m := range f.Members {
			families[m] = f.Name
		}
	}

	var out []MetadataEntry
	for _, d := range defs {
		inst, ok := d.(*InstDef)
		if !ok || inst.Kind != "inst" {
			continue
		}
		pops, pushes := stackCounts(inst.Inputs, inst.Outputs)
		out = append(out, MetadataEntry{
			Name:      inst.Name,
			Pushes:    pushes,
			Pops:      pops,
			CacheSize: cacheCount(inst.Inputs),
			HasOparg:  hasOparg(inst.Body),
			Family:    families[inst.Name],
		})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out
}

// EmitMetadataFile renders entries as a Go source file in pkg, with
// hash stamped in the preamble for B8 drift checking.
func EmitMetadataFile(pkg, hash string, entries []MetadataEntry) string {
	var b strings.Builder
	b.WriteString("// Code generated by tools/bytecodes_gen. DO NOT EDIT.\n")
	b.WriteString(MarkerLine(hash))
	b.WriteString("\npackage " + pkg + "\n\n")
	b.WriteString("// Metadata is the static stack-effect / cache / oparg shape\n")
	b.WriteString("// of every Tier-1 opcode, emitted from Python/bytecodes.c.\n")
	b.WriteString("type Metadata struct {\n")
	b.WriteString("\tName      string\n\tPushes    int\n\tPops      int\n")
	b.WriteString("\tCacheSize int\n\tHasOparg  bool\n\tFamily    string\n}\n\n")
	b.WriteString("var BytecodeMetadata = []Metadata{\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "\t{%q, %d, %d, %d, %t, %q},\n",
			e.Name, e.Pushes, e.Pops, e.CacheSize, e.HasOparg, e.Family)
	}
	b.WriteString("}\n")
	return b.String()
}
